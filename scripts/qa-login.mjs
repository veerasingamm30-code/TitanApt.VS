#!/usr/bin/env node
// Re-authenticates the QA account and writes a curl-compatible (Netscape) cookie jar.
// Usage: node scripts/qa-login.mjs [email] [password]
import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import path from 'node:path';

const email = process.argv[2] ?? 'qa-streaker-1108@titanapt.local';
const password = process.argv[3] ?? 'TitanQA2026x';
const base = 'http://localhost:4000';
const jarPath = path.join(tmpdir(), 'qa-cookies.txt');

function parseSetCookies(res) {
  // undici exposes getSetCookie() on Headers
  const setCookies = res.headers.getSetCookie?.() ?? [];
  return setCookies;
}

const csrfRes = await fetch(`${base}/api/auth/csrf`);
const { token } = await csrfRes.json();
const csrfCookies = parseSetCookies(csrfRes);

const loginRes = await fetch(`${base}/api/auth/login`, {
  method: 'POST',
  headers: {
    'content-type': 'application/json',
    'x-csrf-token': token,
    cookie: csrfCookies.join('; '),
  },
  body: JSON.stringify({ email, password }),
});
if (!loginRes.ok) {
  console.error(`login failed: ${loginRes.status} ${await loginRes.text()}`);
  process.exit(1);
}
const loginCookies = [...csrfCookies, ...parseSetCookies(loginRes)];

// Netscape-format jar for curl.exe
const lines = ['# Netscape HTTP Cookie File (generated by scripts/qa-login.mjs)'];
for (const cookie of loginCookies) {
  const [nameValue] = cookie.split(';');
  const eq = nameValue.indexOf('=');
  const name = nameValue.slice(0, eq);
  const value = nameValue.slice(eq + 1);
  lines.push(`localhost\tFALSE\t/\tFALSE\t0\t${name}\t${value}`);
}
writeFileSync(jarPath, `${lines.join('\n')}\n`, 'utf8');
console.log(`login ok; cookie jar written to ${jarPath} (${loginCookies.length} cookies)`);
